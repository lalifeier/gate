// 出口归属判定：住宅 / 机房 / 未知
// 依据是「出口 IP 的运营商名」，不是 VPN Gate 节点名。

const DC_ORG = /SOFTETHER|AMAZON|AWS|GOOGLE|MICROSOFT|AZURE|OVH|HETZNER|DIGITALOCEAN|AKAMAI|CLOUDFLARE|FASTLY|RACKSPACE|LINODE|VULTR|TENCENT|ALIBABA|ORACLE|M247|CONTABO|LEASEWEB|SOFTLAYER|CHOOPA|PSYCHZ|GTHOST|SERVER|HOSTING|CLOUD|VPS|DATACENTER|DATA ?CENTER|IDC/i;

const RES_ORG = /NTT|KDDI|SOFTBANK|DOCOMO|COMCAST|VERIZON|AT&T|CENTURYLINK|CHARTER|CHUNGHWA|HINET|CHINA ?TELECOM|CHINA ?UNICOM|CHINA ?MOBILE|KORNET|SK ?BROADBAND|LG ?U\+|BIGLOBE|OCN|FRONTIER|SPECTRUM|COX|CENTURY|TOKAI|SO-NET|SONET|PLALA|ASAHI ?NET|ARTERIA|SAKURA|J:COM|JCOM|EONET|DTI|NIFTY|IIJ|INTERLINK|MEGAEGG|AU ?ONE ?NET|NURO|FREEBIT|HIKARI|FIBER|BROADBAND|CABLE|COMMUNICATIONS CORPORATION|TELECOM|DENSAN|KYODOU|KYODO|NETWORK ?SERVICE|INTERNET ?SERVICE|ISP|HOMENET|NTT$/i;

export function classifyExit(org) {
	const o = String(org || '').toUpperCase();
	if (!o) return 'unknown';
	if (DC_ORG.test(o)) return 'datacenter';
	if (RES_ORG.test(o)) return 'residential';
	return 'unknown';
}
